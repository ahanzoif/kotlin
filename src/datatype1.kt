fun main() {
    val a: Int = 10
    val temperature: Double = 37.8
    val isRaining: Boolean = true
    val message: String = "Hello World"
    val alphabet: Char = 'A'
    println("a is Int Data Type ( $a )")
    println("temperature is Double Data Type ( $temperature )")
    println("isRaining is Boolean Data Type ( $isRaining )")
    println("message is String Data Type ( $message )")
    println("alphabet is Char Data Type ( $alphabet )")
}